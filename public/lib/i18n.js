/**
 * Translations for the web UI, the gate page and server-side texts
 * (notification titles, event notes). One module for both sides: the browser
 * imports it as ES module, the server imports the same file from Node.
 *
 * Language choice — by the user's locale, nothing else:
 *   ru                                      → Russian
 *   th                                      → Thai
 *   sr, hr, bs, cnr, mk, sl (ex-Yugoslavia)  → Serbian (Latin script, readable across the region)
 *   everything else                         → English
 * A region alone (en-RS, en-TH) also counts, so a phone set to English in
 * Belgrade still gets Serbian; explicit `?lang=` / saved choice overrides.
 */

export const LANGS = ['en', 'ru', 'th', 'sr'];

const SERBIAN_LANGS = new Set(['sr', 'hr', 'bs', 'cnr', 'mk', 'sl', 'sh']);
const SERBIAN_REGIONS = new Set(['RS', 'HR', 'BA', 'ME', 'MK', 'SI', 'XK']);

/** Locale tag for Intl formatting per UI language. */
export const INTL_LOCALE = { en: 'en-GB', ru: 'ru-RU', th: 'th-TH', sr: 'sr-Latn-RS' };

/**
 * @param {string[]} candidates BCP 47 tags in order of preference
 * @returns {'en'|'ru'|'th'|'sr'}
 */
export function pickLang(candidates = []) {
  const tags = candidates.map((c) => String(c || '').trim()).filter(Boolean);
  for (const tag of tags) {
    const [lang] = tag.toLowerCase().split(/[-_]/);
    if (lang === 'ru') return 'ru';
    if (lang === 'th') return 'th';
    if (SERBIAN_LANGS.has(lang)) return 'sr';
  }
  for (const tag of tags) {
    const parts = tag.split(/[-_]/);
    const region = parts.find((p, i) => i > 0 && /^[A-Za-z]{2}$/.test(p))?.toUpperCase();
    if (region === 'TH') return 'th';
    if (region && SERBIAN_REGIONS.has(region)) return 'sr';
    if (region === 'RU') return 'ru';
  }
  return 'en';
}

/** "ru-RU,ru;q=0.9,en;q=0.8" → ['ru-RU', 'ru', 'en'] */
export function parseAcceptLanguage(header = '') {
  return String(header)
    .split(',')
    .map((part) => {
      const [tag, ...params] = part.trim().split(';');
      const q = params.map((p) => p.trim()).find((p) => p.startsWith('q='));
      return { tag: tag.trim(), q: q ? Number(q.slice(2)) || 0 : 1 };
    })
    .filter((x) => x.tag && x.tag !== '*')
    .sort((a, b) => b.q - a.q)
    .map((x) => x.tag);
}

export function isLang(x) {
  return LANGS.includes(x);
}

/** @returns {(key: string, params?: Record<string, string|number>) => string} */
export function translator(lang) {
  const table = MESSAGES[isLang(lang) ? lang : 'en'];
  return (key, params = {}) => {
    let text = table[key] ?? MESSAGES.en[key] ?? key;
    for (const [k, v] of Object.entries(params)) text = text.split(`{${k}}`).join(String(v));
    return text;
  };
}

